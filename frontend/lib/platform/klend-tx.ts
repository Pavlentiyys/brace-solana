/**
 * The KLend instructions needed to open a position, built by hand.
 *
 * Reading Kamino needs no library at all — `kamino.ts` decodes accounts by offset
 * over plain JSON-RPC. Writing needs a transaction, and a transaction needs an
 * assembler, so this is the one place `@solana/web3.js` earns its bundle weight. It
 * is imported only by the `/chat` write path.
 *
 * There is still no Anchor here. An Anchor instruction is an 8-byte discriminator —
 * `sha256("global:" + snake_case_name)[..8]` — followed by borsh arguments, and every
 * argument on this path is a `u64` or two `u8`s. The discriminators below were
 * generated by Anchor's own coder from `tools/devnet/idl/klend.json` and are pinned
 * by `klend-tx.test.ts` against the same hash.
 *
 * Account orders come from that IDL and are exercised end to end: the same sequence,
 * built by the same rules, opened the position in `tools/devnet/src/open-position.ts`.
 */

import {
  PublicKey,
  SystemProgram,
  SYSVAR_INSTRUCTIONS_PUBKEY,
  SYSVAR_RENT_PUBKEY,
  TransactionInstruction,
} from "@solana/web3.js";

import { KLEND_PROGRAM_ID as KLEND_ID } from "@/lib/platform/kamino";

export const KLEND_PROGRAM_ID = new PublicKey(KLEND_ID);
export const TOKEN_PROGRAM_ID = new PublicKey("TokenkegQfeZyiNwAJbNbGKPFXCWuBvf9Ss623VQ5DA");
export const ASSOCIATED_TOKEN_PROGRAM_ID = new PublicKey(
  "ATokenGPvbdGVxr1b2hvZbsiqW5xWH25efTNsLJA8knL",
);
export const FARMS_PROGRAM_ID = new PublicKey("FarmsPZpWu9i7Kky8tPN37rs2TpmMrAZrC7S7vJa91Hr");
export const U64_MAX = 2n ** 64n - 1n;

/** `sha256("global:" + name)[..8]`, cross-checked against Anchor's coder. */
export const DISCRIMINATORS = {
  initUserMetadata: [117, 169, 176, 69, 197, 23, 15, 162],
  initObligation: [251, 10, 231, 76, 27, 11, 159, 96],
  refreshReserve: [2, 218, 138, 235, 79, 201, 25, 102],
  refreshObligation: [33, 132, 147, 228, 151, 192, 72, 89],
  depositReserveLiquidityAndObligationCollateral: [129, 199, 4, 2, 222, 39, 26, 46],
  borrowObligationLiquidity: [121, 127, 18, 204, 73, 245, 225, 65],
  repayObligationLiquidityV2: [116, 174, 213, 76, 180, 53, 210, 144],
  withdrawObligationCollateralAndRedeemReserveCollateralV2: [
    235, 52, 119, 152, 149, 197, 20, 7,
  ],
} as const;

const SEEDS = {
  marketAuthority: "lma",
  liquiditySupply: "reserve_liq_supply",
  feeReceiver: "fee_receiver",
  collateralMint: "reserve_coll_mint",
  collateralSupply: "reserve_coll_supply",
  userMetadata: "user_meta",
} as const;

function pda(seed: string, ...rest: PublicKey[]): PublicKey {
  return PublicKey.findProgramAddressSync(
    [seedBytes(seed), ...rest.map((key) => key.toBuffer())],
    KLEND_PROGRAM_ID,
  )[0];
}

export function marketAuthority(market: PublicKey): PublicKey {
  return pda(SEEDS.marketAuthority, market);
}

export function userMetadata(owner: PublicKey): PublicKey {
  return pda(SEEDS.userMetadata, owner);
}

/** Seeded by the reserve address alone, not by the market and mint. */
export function reserveAccounts(reserve: PublicKey) {
  return {
    liquiditySupply: pda(SEEDS.liquiditySupply, reserve),
    feeReceiver: pda(SEEDS.feeReceiver, reserve),
    collateralMint: pda(SEEDS.collateralMint, reserve),
    collateralSupply: pda(SEEDS.collateralSupply, reserve),
  };
}

/** A vanilla obligation: tag 0, id 0, and two zeroed seeds. */
export function obligationAddress(owner: PublicKey, market: PublicKey): PublicKey {
  return PublicKey.findProgramAddressSync(
    [
      Uint8Array.of(0),
      Uint8Array.of(0),
      owner.toBuffer(),
      market.toBuffer(),
      PublicKey.default.toBuffer(),
      PublicKey.default.toBuffer(),
    ],
    KLEND_PROGRAM_ID,
  )[0];
}

export function associatedTokenAddress(mint: PublicKey, owner: PublicKey): PublicKey {
  return PublicKey.findProgramAddressSync(
    [owner.toBuffer(), TOKEN_PROGRAM_ID.toBuffer(), mint.toBuffer()],
    ASSOCIATED_TOKEN_PROGRAM_ID,
  )[0];
}

/**
 * Instruction data, assembled without Node's `Buffer` methods.
 *
 * In the browser `Buffer` is a polyfill, and the one bundled here has no
 * `writeBigUInt64LE` — so the obvious `Buffer.alloc(8).writeBigUInt64LE(amount)`
 * works in Node, passes every test, and then throws the moment a real wallet is
 * asked to sign. `DataView` is part of the language and behaves the same in both.
 *
 * The result is wrapped back into a `Buffer` at the very end because that is what
 * web3.js types `TransactionInstruction.data` as.
 */
function data(discriminator: readonly number[], ...rest: Uint8Array[]): Buffer {
  const total = discriminator.length + rest.reduce((sum, part) => sum + part.length, 0);
  const bytes = new Uint8Array(total);
  bytes.set(discriminator, 0);

  let offset = discriminator.length;
  for (const part of rest) {
    bytes.set(part, offset);
    offset += part.length;
  }
  return Buffer.from(bytes);
}

function u64(value: bigint): Uint8Array {
  const bytes = new Uint8Array(8);
  new DataView(bytes.buffer).setBigUint64(0, value, true);
  return bytes;
}

/** Seeds have to be bytes; `Buffer.from(string)` is the polyfill path to avoid. */
function seedBytes(seed: string): Uint8Array {
  return new TextEncoder().encode(seed);
}

const ro = (pubkey: PublicKey) => ({ pubkey, isSigner: false, isWritable: false });
const rw = (pubkey: PublicKey) => ({ pubkey, isSigner: false, isWritable: true });
const sig = (pubkey: PublicKey, isWritable = true) => ({ pubkey, isSigner: true, isWritable });

/** Creates the recipient's token account if it is missing. Safe to always include. */
export function createAtaIdempotent(payer: PublicKey, owner: PublicKey, mint: PublicKey) {
  return new TransactionInstruction({
    programId: ASSOCIATED_TOKEN_PROGRAM_ID,
    keys: [
      sig(payer),
      rw(associatedTokenAddress(mint, owner)),
      ro(owner),
      ro(mint),
      ro(SystemProgram.programId),
      ro(TOKEN_PROGRAM_ID),
    ],
    // 1 is CreateIdempotent; 0 would fail on an account that already exists.
    data: Buffer.from(Uint8Array.of(1)),
  });
}

export function initUserMetadataIx(owner: PublicKey) {
  return new TransactionInstruction({
    programId: KLEND_PROGRAM_ID,
    keys: [
      sig(owner, false),
      sig(owner),
      rw(userMetadata(owner)),
      // Anchor writes an absent optional account as the program's own id.
      ro(KLEND_PROGRAM_ID),
      ro(SYSVAR_RENT_PUBKEY),
      ro(SystemProgram.programId),
    ],
    data: data(DISCRIMINATORS.initUserMetadata, PublicKey.default.toBuffer()),
  });
}

export function initObligationIx(owner: PublicKey, market: PublicKey) {
  return new TransactionInstruction({
    programId: KLEND_PROGRAM_ID,
    keys: [
      sig(owner, false),
      sig(owner),
      rw(obligationAddress(owner, market)),
      ro(market),
      ro(PublicKey.default),
      ro(PublicKey.default),
      ro(userMetadata(owner)),
      ro(SYSVAR_RENT_PUBKEY),
      ro(SystemProgram.programId),
    ],
    data: data(DISCRIMINATORS.initObligation, Uint8Array.of(0, 0)),
  });
}

export function refreshReserveIx(reserve: PublicKey, market: PublicKey, pythFeed: PublicKey) {
  return new TransactionInstruction({
    programId: KLEND_PROGRAM_ID,
    keys: [
      rw(reserve),
      ro(market),
      ro(pythFeed),
      ro(KLEND_PROGRAM_ID),
      ro(KLEND_PROGRAM_ID),
      ro(KLEND_PROGRAM_ID),
    ],
    data: data(DISCRIMINATORS.refreshReserve),
  });
}

/**
 * Refreshes the obligation against exactly the reserves it currently references.
 *
 * Deposits first, then borrows. KLend rejects any other set or order with
 * `InvalidAccountInput`, so the caller has to read the obligation rather than guess.
 */
export function refreshObligationIx(
  obligation: PublicKey,
  market: PublicKey,
  reserves: PublicKey[],
) {
  return new TransactionInstruction({
    programId: KLEND_PROGRAM_ID,
    keys: [ro(market), rw(obligation), ...reserves.map(rw)],
    data: data(DISCRIMINATORS.refreshObligation),
  });
}

export function depositIx(input: {
  owner: PublicKey;
  market: PublicKey;
  reserve: PublicKey;
  liquidityMint: PublicKey;
  amount: bigint;
}) {
  const pdas = reserveAccounts(input.reserve);
  return new TransactionInstruction({
    programId: KLEND_PROGRAM_ID,
    keys: [
      sig(input.owner),
      rw(obligationAddress(input.owner, input.market)),
      ro(input.market),
      ro(marketAuthority(input.market)),
      rw(input.reserve),
      ro(input.liquidityMint),
      rw(pdas.liquiditySupply),
      rw(pdas.collateralMint),
      rw(pdas.collateralSupply),
      rw(associatedTokenAddress(input.liquidityMint, input.owner)),
      // `placeholderUserDestinationCollateral`, absent.
      ro(KLEND_PROGRAM_ID),
      ro(TOKEN_PROGRAM_ID),
      ro(TOKEN_PROGRAM_ID),
      ro(SYSVAR_INSTRUCTIONS_PUBKEY),
    ],
    data: data(DISCRIMINATORS.depositReserveLiquidityAndObligationCollateral, u64(input.amount)),
  });
}

export function borrowIx(input: {
  owner: PublicKey;
  market: PublicKey;
  reserve: PublicKey;
  liquidityMint: PublicKey;
  amount: bigint;
}) {
  const pdas = reserveAccounts(input.reserve);
  return new TransactionInstruction({
    programId: KLEND_PROGRAM_ID,
    keys: [
      sig(input.owner, false),
      rw(obligationAddress(input.owner, input.market)),
      ro(input.market),
      ro(marketAuthority(input.market)),
      rw(input.reserve),
      ro(input.liquidityMint),
      rw(pdas.liquiditySupply),
      rw(pdas.feeReceiver),
      rw(associatedTokenAddress(input.liquidityMint, input.owner)),
      // `referrerTokenState`, absent.
      ro(KLEND_PROGRAM_ID),
      ro(TOKEN_PROGRAM_ID),
      ro(SYSVAR_INSTRUCTIONS_PUBKEY),
    ],
    data: data(DISCRIMINATORS.borrowObligationLiquidity, u64(input.amount)),
  });
}

/** Repays a borrow from the owner's own debt token account. */
export function repayObligationLiquidityV2Ix(input: {
  owner: PublicKey;
  obligation: PublicKey;
  market: PublicKey;
  reserve: PublicKey;
  liquidityMint: PublicKey;
  amount: bigint;
  /** The obligation's deposit reserves, passed as KLend remaining accounts. */
  depositReserves: PublicKey[];
}) {
  const pdas = reserveAccounts(input.reserve);
  return new TransactionInstruction({
    programId: KLEND_PROGRAM_ID,
    keys: [
      sig(input.owner, false),
      rw(input.obligation),
      ro(input.market),
      rw(input.reserve),
      ro(input.liquidityMint),
      rw(pdas.liquiditySupply),
      rw(associatedTokenAddress(input.liquidityMint, input.owner)),
      ro(TOKEN_PROGRAM_ID),
      ro(SYSVAR_INSTRUCTIONS_PUBKEY),
      // Optional farm accounts. Anchor's None convention is the KLend program id.
      ro(KLEND_PROGRAM_ID),
      ro(KLEND_PROGRAM_ID),
      ro(marketAuthority(input.market)),
      ro(FARMS_PROGRAM_ID),
      ...input.depositReserves.map(rw),
    ],
    data: data(DISCRIMINATORS.repayObligationLiquidityV2, u64(input.amount)),
  });
}

/** Withdraws all collateral and redeems it to the owner's underlying-token ATA. */
export function withdrawObligationCollateralAndRedeemReserveCollateralV2Ix(input: {
  owner: PublicKey;
  obligation: PublicKey;
  market: PublicKey;
  reserve: PublicKey;
  liquidityMint: PublicKey;
  collateralAmount: bigint;
}) {
  const pdas = reserveAccounts(input.reserve);
  return new TransactionInstruction({
    programId: KLEND_PROGRAM_ID,
    keys: [
      sig(input.owner),
      rw(input.obligation),
      ro(input.market),
      ro(marketAuthority(input.market)),
      rw(input.reserve),
      ro(input.liquidityMint),
      rw(pdas.collateralSupply),
      rw(pdas.collateralMint),
      rw(pdas.liquiditySupply),
      rw(associatedTokenAddress(input.liquidityMint, input.owner)),
      // Optional destination collateral and farm accounts are absent.
      ro(KLEND_PROGRAM_ID),
      ro(TOKEN_PROGRAM_ID),
      ro(TOKEN_PROGRAM_ID),
      ro(SYSVAR_INSTRUCTIONS_PUBKEY),
      ro(KLEND_PROGRAM_ID),
      ro(KLEND_PROGRAM_ID),
      ro(FARMS_PROGRAM_ID),
    ],
    data: data(
      DISCRIMINATORS.withdrawObligationCollateralAndRedeemReserveCollateralV2,
      u64(input.collateralAmount),
    ),
  });
}
